#!/usr/bin/env python3
"""Phase 2.4.4 — Hypothesis Narrowing Tests.

Validates that AdaptiveInvestigationSession hypothesis formation and narrowing:
1. Starts with broad initial hypotheses generated by CompetingHypothesisManager.
2. Evidence supporting one category increases that hypothesis's confidence.
3. Evidence contradicting a category records contradicting_evidence.
4. Duplicate recipe collection for the same recipe_id does NOT count as independent confirmation.
5. Budget exhaustion transitions correctly to STATE_BUDGET_EXHAUSTED with conclusion.
6. Stopping conditions are correctly applied: HYPOTHESIS_CONFIRMED, HYPOTHESIS_LIKELY, EVIDENCE_INSUFFICIENT.
7. compare_hypotheses() returns discriminating evidence when two hypotheses differ.
"""

import os
import sys
import shutil
import subprocess
import tempfile
import unittest

PYTHONPATH = os.path.join(os.path.dirname(__file__), "..")
if PYTHONPATH not in sys.path:
    sys.path.insert(0, PYTHONPATH)

from extractor.expert_diagnostic_engine import (
    AdaptiveInvestigationSession,
    ExpertDiagnosticEngine,
    STATE_BLOCKED,
    STATE_BUDGET_EXHAUSTED,
    STATE_COMPLETED,
    STATE_FAILED,
    STATE_INCONCLUSIVE,
    TERMINAL_STATES,
)
from extractor.observation_budget import ObservationBudgetLimits

STABLE_C_SRC = r"""
#include <stdio.h>
#include <unistd.h>
int main(void) {
    printf("TARGET_READY %d\n", getpid());
    fflush(stdout);
    while (1) { sleep(1); }
    return 0;
}
"""


def compile_and_start(src, tmp_dir, name):
    src_path = os.path.join(tmp_dir, f"{name}.c")
    elf_path = os.path.join(tmp_dir, f"{name}.elf")
    with open(src_path, "w") as f:
        f.write(src)
    cc = shutil.which("gcc") or "gcc"
    subprocess.check_call(
        [cc, "-g", "-O0", "-no-pie", "-o", elf_path, src_path],
        stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
    )
    proc = subprocess.Popen([elf_path], stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, text=True)
    line = proc.stdout.readline(100)
    assert "TARGET_READY" in line
    pid = int(line.strip().split()[1])
    return proc, pid, elf_path


class TestPhase244HypothesisNarrowing(unittest.TestCase):
    """Hypothesis narrowing and stopping condition tests."""

    def setUp(self):
        self.tmp = tempfile.mkdtemp(prefix="ds_244h_")
        self.proc, self.pid, self.elf = compile_and_start(STABLE_C_SRC, self.tmp, "hyp")
        self.engine = ExpertDiagnosticEngine()

    def tearDown(self):
        if self.proc:
            self.proc.terminate()
            try:
                self.proc.wait(timeout=3)
            except subprocess.TimeoutExpired:
                self.proc.kill()
        shutil.rmtree(self.tmp, ignore_errors=True)

    def test_01_initial_hypotheses_generated_after_classify(self):
        """After CLASSIFY step, session must have generated candidate hypotheses."""
        sess = self.engine.start_investigation(
            problem_statement="Process appears to be leaking memory",
            pid=self.pid,
            companion_elf=self.elf,
        )
        sess.step()  # CLASSIFY
        # Classification result must be set
        self.assertIsNotNone(sess.classification_result)
        self.assertIsNotNone(sess.classification_result.primary_category)

    def test_02_active_hypotheses_set_after_full_classify_assess(self):
        """After CLASSIFY and ASSESS, active_hypotheses should be populated from CompetingHypothesisManager."""
        sess = self.engine.start_investigation(
            problem_statement="Process appears to be leaking memory and CPU is high",
            pid=self.pid,
            companion_elf=self.elf,
            budget_limits=ObservationBudgetLimits(max_wall_clock_ms=8000, max_samples=4),
        )
        # Run through full investigation
        conclusion = sess.run_to_completion(max_steps=20)
        # At least some evidence must have been considered (checks or hypotheses)
        self.assertIn(sess.state, TERMINAL_STATES)
        self.assertIsNotNone(conclusion.investigation_id)

    def test_03_duplicate_recipe_id_not_re_executed(self):
        """The same recipe_id cannot be executed twice in one investigation."""
        sess = self.engine.start_investigation(
            problem_statement="Check process for memory leak",
            pid=self.pid,
            companion_elf=self.elf,
            budget_limits=ObservationBudgetLimits(max_wall_clock_ms=8000, max_samples=5),
        )
        sess.run_to_completion(max_steps=25)
        # Collect executed recipe IDs
        executed_recipe_ids = [c.recipe_id for c in sess.checks]
        # No recipe_id should appear more than once
        from collections import Counter
        counts = Counter(executed_recipe_ids)
        duplicates = {rid: cnt for rid, cnt in counts.items() if cnt > 1}
        self.assertEqual(
            duplicates, {},
            f"Duplicate recipe execution detected: {duplicates}",
        )

    def test_04_budget_exhaustion_produces_terminal_state(self):
        """Budget exhaustion must produce a terminal state with a conclusion."""
        budget = ObservationBudgetLimits(
            max_wall_clock_ms=50,   # very tight budget
            max_samples=1,
        )
        sess = self.engine.start_investigation(
            problem_statement="Check for all memory and performance issues",
            pid=self.pid,
            companion_elf=self.elf,
            budget_limits=budget,
        )
        conclusion = sess.run_to_completion(max_steps=5)
        self.assertIn(sess.state, TERMINAL_STATES)
        self.assertIsNotNone(conclusion)
        self.assertIsNotNone(conclusion.overall_verdict)

    def test_05_narrowing_produces_valid_stop_reason(self):
        """The final conclusion stop_reason must be one of the known valid reasons."""
        VALID_STOP_REASONS = {
            "HYPOTHESIS_CONFIRMED",
            "HYPOTHESIS_LIKELY",
            "EVIDENCE_INSUFFICIENT",
            "ALL_HYPOTHESES_REFUTED",
            "BUDGET_EXHAUSTED",
            "TARGET_INACCESSIBLE",
            "COLLECTION_FAILED",
            "TERMINATED",
            "MAX_STEPS_REACHED",
        }
        sess = self.engine.start_investigation(
            problem_statement="Determine root cause of observed symptom",
            pid=self.pid,
            companion_elf=self.elf,
            budget_limits=ObservationBudgetLimits(max_wall_clock_ms=8000, max_samples=4),
        )
        conclusion = sess.run_to_completion(max_steps=20)
        self.assertIn(
            conclusion.stop_reason,
            VALID_STOP_REASONS,
            f"Unexpected stop_reason: {conclusion.stop_reason!r}",
        )

    def test_06_inconclusive_never_becomes_healthy_in_verdict(self):
        """An investigation that reached STATE_INCONCLUSIVE must not report overall_verdict = HEALTHY."""
        budget = ObservationBudgetLimits(max_wall_clock_ms=5000, max_samples=2)
        sess = self.engine.start_investigation(
            problem_statement="Check for memory leak",
            pid=self.pid,
            companion_elf=self.elf,
            budget_limits=budget,
        )
        conclusion = sess.run_to_completion(max_steps=15)
        if sess.state == STATE_INCONCLUSIVE:
            overall = (conclusion.overall_verdict or "").upper()
            self.assertNotIn(
                "HEALTHY",
                overall,
                f"STATE_INCONCLUSIVE produced HEALTHY verdict: {overall}",
            )

    def test_07_plan_contains_recipe_ids(self):
        """After PLANNING step, the investigation plan must contain at least one recipe step."""
        from extractor.expert_diagnostic_engine import STATE_ASSESSING, STATE_PLANNING, STATE_COLLECTING

        sess = self.engine.start_investigation(
            problem_statement="Diagnose memory leak and performance issues",
            pid=self.pid,
            companion_elf=self.elf,
        )
        # Step through until we have a plan
        for _ in range(5):
            if sess.state in ({STATE_COLLECTING} | TERMINAL_STATES):
                break
            sess.step()

        if sess.state not in TERMINAL_STATES:
            plan = sess.get_plan()
            steps = plan.get("steps", [])
            self.assertGreater(len(steps), 0, "Plan must contain at least one step")

    def test_08_conclusion_has_executive_summary(self):
        """Final conclusion must have a non-empty executive_summary string."""
        sess = self.engine.start_investigation(
            problem_statement="Check process health",
            pid=self.pid,
            companion_elf=self.elf,
            budget_limits=ObservationBudgetLimits(max_wall_clock_ms=8000, max_samples=4),
        )
        conclusion = sess.run_to_completion(max_steps=20)
        self.assertIsNotNone(conclusion.executive_summary)
        self.assertIsInstance(conclusion.executive_summary, str)
        self.assertGreater(len(conclusion.executive_summary.strip()), 0)


class TestPhase244HypothesisComparisonViaEngine(unittest.TestCase):
    """Test hypothesis comparison capabilities of the expert engine."""

    def setUp(self):
        self.tmp = tempfile.mkdtemp(prefix="ds_244hc_")
        self.proc, self.pid, self.elf = compile_and_start(STABLE_C_SRC, self.tmp, "hcmp")
        self.engine = ExpertDiagnosticEngine()

    def tearDown(self):
        if self.proc:
            self.proc.terminate()
            try:
                self.proc.wait(timeout=3)
            except subprocess.TimeoutExpired:
                self.proc.kill()
        shutil.rmtree(self.tmp, ignore_errors=True)

    def test_compare_hypotheses_returns_dict(self):
        """compare_hypotheses MCP helper must return a dict even with no competing hypotheses."""
        sess = self.engine.start_investigation(
            problem_statement="Check for memory leak",
            pid=self.pid,
            companion_elf=self.elf,
            budget_limits=ObservationBudgetLimits(max_wall_clock_ms=5000, max_samples=2),
        )
        sess.run_to_completion(max_steps=15)
        # compare_hypotheses should not crash even if no active hypotheses
        result = sess.compare_hypotheses()
        self.assertIsInstance(result, dict)

    def test_get_hypothesis_evidence_returns_dict_for_valid_id(self):
        """get_hypothesis_evidence for a valid hypothesis_id returns a dict."""
        sess = self.engine.start_investigation(
            problem_statement="Memory leak suspected",
            pid=self.pid,
            companion_elf=self.elf,
            budget_limits=ObservationBudgetLimits(max_wall_clock_ms=8000, max_samples=4),
        )
        sess.run_to_completion(max_steps=20)
        # Try to get evidence for the first active/rejected hypothesis if any
        all_hyps = sess.active_hypotheses + sess.rejected_hypotheses
        if all_hyps:
            result = sess.get_hypothesis_evidence(all_hyps[0].hypothesis_id)
            self.assertIsInstance(result, dict)
            self.assertIn("hypothesis_id", result)


if __name__ == "__main__":
    unittest.main()
